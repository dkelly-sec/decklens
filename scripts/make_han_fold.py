"""Build src/decklens/han_fold.py from OpenCC's character tables.

Japanese, traditional and simplified Chinese write many of the same characters
differently (単 / 單 / 单). Search folds them all to the simplified form, so a
name typed or read in one form finds the player whatever form their name uses.

    python scripts/make_han_fold.py OPENCC_DICTIONARY_DIR COMMIT

OPENCC_DICTIONARY_DIR holds these files from OpenCC's data/dictionary folder
(https://github.com/BYVoid/OpenCC, Apache-2.0) at COMMIT: TSCharacters.txt,
TWVariants.txt, HKVariants.txt and JPShinjitaiCharacters.txt. After running it,
stored names need new keys once: python -m decklens.reindex.
"""

from __future__ import annotations

import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "decklens" / "han_fold.py"


def read_table(path: Path) -> dict[str, list[str]]:
    table = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        key, values = line.split("\t")
        if len(key) == 1:   # single characters only
            table[key] = [v for v in values.split(" ") if len(v) == 1]
    return table


def build(folder: Path) -> dict[str, str]:
    to_simplified = {t: v[0] for t, v in read_table(folder / "TSCharacters.txt").items() if v}
    fold: dict[str, str] = dict(to_simplified)
    # Taiwan / Hong Kong forms (key: OpenCC's standard traditional form, value: the
    # regional form): the regional form folds like the standard one.
    for name in ("TWVariants.txt", "HKVariants.txt"):
        for standard, forms in read_table(folder / name).items():
            for form in forms:
                if form != standard:
                    fold.setdefault(form, to_simplified.get(standard, standard))
    # Japanese new forms (key) -> traditional (first value). A first value equal to
    # the key is kept by OpenCC for compatibility: nothing to fold.
    for shinjitai, forms in read_table(folder / "JPShinjitaiCharacters.txt").items():
        if forms and forms[0] != shinjitai:
            fold.setdefault(shinjitai, to_simplified.get(forms[0], forms[0]))

    def settle(ch: str) -> str:
        """Follow chains (a -> b -> c) to the end; a loop (叙 -> 敍 -> 叙) settles
        on its lowest character, so every member folds to the same one."""
        path = [ch]
        while ch in fold:
            ch = fold[ch]
            if ch in path:
                return min(path[path.index(ch):])
            path.append(ch)
        return ch

    return {k: v for k in sorted(fold) if (v := settle(k)) != k}


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    folder, commit = Path(argv[0]), argv[1]
    fold = build(folder)
    keys, values = "".join(fold), "".join(fold.values())
    lines = [keys[i:i + 60] for i in range(0, len(keys), 60)]
    vals = [values[i:i + 60] for i in range(0, len(values), 60)]
    body = "\n".join(f'    "{k}"' for k in lines)
    vbody = "\n".join(f'    "{v}"' for v in vals)
    OUT.write_text(
        '"""Japanese and traditional Chinese characters -> simplified Chinese (単 -> 单,\n'
        '騎 -> 骑, 黒 -> 黑), so search treats the forms of one character as equal.\n\n'
        "Generated by scripts/make_han_fold.py from OpenCC's character tables\n"
        f"(https://github.com/BYVoid/OpenCC, commit {commit[:12]}), Apache-2.0:\n"
        "OpenCC is by Carbo Kuo (BYVoid) and contributors. Don't edit by hand.\n"
        '"""\n\n'
        f"FROM = (\n{body}\n)\n"
        f"TO = (\n{vbody}\n)\n",
        encoding="utf-8")
    print(f"wrote {len(fold)} characters to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
